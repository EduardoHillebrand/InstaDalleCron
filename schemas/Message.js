const mongoose = require('mongoose');

// Defining the sub-schema for songs
const songSchema = new mongoose.Schema({
  songName: String,
  artistOrBand: String,
  releaseDate: Date
});

// Defining the main schema
const messageSchema = new mongoose.Schema({
  message: String, // the message received to start the process
  imagePath: String, // Path to the image file
  imagePrompt: String, // Text used to generate the image
  hashtags: String, // Text containing multiple hashtags
  musicPrompt: String, // Text for generating a list of songs
  playlistName: String, // Text for the namo of playlist
  status: String, // the position at the line of production
  songs: [songSchema] // List of songs generated by the music prompt
}, { timestamps: true });

// Creating the model based on the schema
const MessageModel = mongoose.model('Message', messageSchema);

module.exports = MessageModel;
